import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import postcss from 'postcss'

const packageDir = new URL('../node_modules/@hito-ds/react/', import.meta.url)
const { version } = JSON.parse(readFileSync(new URL('package.json', packageDir), 'utf8'))
if (version !== '0.2.0') throw new Error(`Review PORT-34 scoping before consuming Hito ${version}`)

const scope = ':where([data-hito-native])'
const sources = ['base.css', 'tokens.css', 'dist/components.css']
const css = sources.map(file => {
  const source = readFileSync(new URL(file, packageDir), 'utf8')
  const root = postcss.parse(source, { from: file })

  // The portfolio reset is unlayered. Keep Hito's source order within the
  // scoped island so the native rules win over generic element resets.
  root.walkAtRules('layer', layer => layer.nodes ? layer.replaceWith(...layer.nodes) : layer.remove())
  root.walkAtRules('scope', rule => {
    const theme = '[data-hito-theme="neutral"]'
    rule.params = rule.params.replace(`(${theme})`, `(${scope}${theme}, ${scope} ${theme})`)
  })
  root.walkRules(rule => {
    for (let ancestor = rule.parent; ancestor; ancestor = ancestor.parent) {
      if (ancestor.type === 'atrule' && /^(scope|(-webkit-)?keyframes)$/.test(ancestor.name)) return
    }
    if (file === 'base.css' && rule.selector === 'body') {
      rule.walkDecls(/^(margin|min-block-size|background)$/, declaration => declaration.remove())
      if (!rule.nodes.length) {
        rule.remove()
        return
      }
    }
    rule.selectors = rule.selectors.flatMap(selector => {
      if (selector.startsWith(':root')) return [scope + selector.slice(':root'.length)]
      if (selector === 'html' || selector === 'body') return [scope]
      if (selector.startsWith('[')) return [scope + selector, `${scope} ${selector}`]
      if (selector.startsWith('*')) return [scope + selector.slice(1), `${scope} ${selector}`]
      return [`${scope} ${selector}`]
    })
  })
  const sha = createHash('sha256').update(source).digest('hex')
  return `/* @hito-ds/react@${version} ${file}, SHA256 ${sha} */\n${root}`
}).join('\n\n')

writeFileSync(new URL('../src/components/hito-case/native.generated.css', import.meta.url),
  `/* Generated by node scripts/scope-hito-styles.mjs. */\n${css}\n`)
